#!/usr/bin/env python3
"""Generate real 192px WebP inputs and external-decoder quality references.

Requires cwebp/dwebp/webpmux, ImageMagick, and Little CMS. Neither libsixel nor
lsqa generates any expected pixel. ICC data comes from the existing A98 input;
Little CMS supplies only the standard sRGB destination profile. Alpha is a
horizontal coverage ramp, composed independently in linear sRGB over #808080.
The shifted controls retain dimensions and color distribution but lose spatial
alignment. --check compares regenerated bytes without replacing fixtures.
"""
import argparse
import ctypes
import ctypes.util
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).resolve().parent


def run(*args):
    return subprocess.check_output([str(arg) for arg in args],
                                   stderr=subprocess.DEVNULL)


def decode(value):
    return value / 12.92 if value <= .04045 else ((value + .055) / 1.055) ** 2.4


def encode(value):
    return value * 12.92 if value <= .0031308 else 1.055 * value ** (1 / 2.4) - .055


def generate(directory):
    source = ROOT / 'tests/data/inputs/snake_192.png'
    original = ROOT / 'tests/data/inputs/snake_64_embedded_a98_icc.webp'
    icc = directory / 'a98.icc'
    srgb = directory / 'srgb.icc'
    run('webpmux', '-get', 'icc', original, '-o', icc)
    cms = ctypes.CDLL(ctypes.util.find_library('lcms2'))
    cms.cmsCreate_sRGBProfile.restype = ctypes.c_void_p
    cms.cmsSaveProfileToFile.argtypes = [ctypes.c_void_p, ctypes.c_char_p]
    cms.cmsCloseProfile.argtypes = [ctypes.c_void_p]
    profile = cms.cmsCreate_sRGBProfile()
    assert profile
    try:
        assert cms.cmsSaveProfileToFile(profile, str(srgb).encode())
    finally:
        cms.cmsCloseProfile(profile)
    run('magick', source, '-alpha', 'set', '-channel', 'A', '-fx',
        'i/(w-1)', '-strip', directory / 'alpha.png')
    outputs = {}
    for name in ('plain', 'icc', 'alpha'):
        webp = directory / 'input.webp'
        png = directory / 'decoded.png'
        run('cwebp', '-quiet', '-q', '90',
            directory / 'alpha.png' if name == 'alpha' else source,
            '-o', webp)
        if name != 'plain':
            tagged = directory / 'tagged.webp'
            run('webpmux', '-set', 'icc', icc, webp, '-o', tagged)
            webp = tagged
        outputs[f'webp-yuv-{name}.webp'] = webp.read_bytes()
        run('dwebp', '-quiet', webp, '-o', png)
        rgba = run('magick', png, '-depth', '8', 'RGBA:-')
        command = ['magick', png, '-alpha', 'off']
        if name != 'plain':
            command += ['-profile', icc, '-profile', srgb]
        rgb = bytearray(run(*command, '-depth', '8', 'RGB:-'))
        assert len(rgb) == 192 * 192 * 3 and len(rgba) == 192 * 192 * 4
        if name == 'alpha':
            background = decode(128 / 255)
            for pixel in range(192 * 192):
                alpha = rgba[pixel * 4 + 3] / 255
                for channel in range(3):
                    at = pixel * 3 + channel
                    value = decode(rgb[at] / 255) * alpha + background * (1 - alpha)
                    rgb[at] = int(min(1, max(0, encode(value))) * 255 + .5)
        header = b'P6\n192 192\n255\n'
        outputs[f'webp-yuv-{name}.ppm'] = header + rgb
        shifted = bytearray()
        for y in range(192):
            row = rgb[y * 576:(y + 1) * 576]
            shifted += row[24:] + row[:24]
        outputs[f'webp-yuv-{name}-shifted.ppm'] = header + shifted
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as directory:
        for name, data in generate(Path(directory)).items():
            path = HERE / name
            if args.check:
                assert path.read_bytes() == data, path
            else:
                path.write_bytes(data)


if __name__ == '__main__':
    main()
