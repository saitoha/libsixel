"""Emit spatial CIEDE2000 fixtures using independent dense NumPy filters.

Run offline, never from TAP. scielab_reference supplies the independent
2-D spatial filter, physical XYZ D50 and Lab conversion. This vectorized
CIEDE2000 equation uses kL=kC=kH=1 and does not import production code.
See Johnson/Fairchild, DOI 10.1002/col.10195, and Sharma/Wu/Dalal,
DOI 10.1002/col.20070, for composition and hue-branch conventions.
"""
import itertools
import numpy as np
from scielab_reference import emit, filtered_lab


def de00(a, b):
    l1, a1, b1 = np.moveaxis(a, -1, 0)
    l2, a2, b2 = np.moveaxis(b, -1, 0)
    chroma = (np.hypot(a1, b1) + np.hypot(a2, b2)) / 2
    g = (1 - np.sqrt(chroma**7 / (chroma**7 + 25**7))) / 2
    a1, a2 = (1 + g) * a1, (1 + g) * a2
    c1, c2 = np.hypot(a1, b1), np.hypot(a2, b2)
    h1 = np.mod(np.degrees(np.arctan2(b1, a1)), 360)
    h2 = np.mod(np.degrees(np.arctan2(b2, a2)), 360)
    h1, h2 = np.where(c1 == 0, 0, h1), np.where(c2 == 0, 0, h2)
    dh = h2 - h1
    dh = np.where(dh > 180, dh - 360, np.where(dh < -180, dh + 360, dh))
    dh = np.where(c1 * c2 == 0, 0, dh)
    delta_h = 2 * np.sqrt(c1 * c2) * np.sin(np.radians(dh) / 2)
    lbar, cbar = (l1 + l2) / 2, (c1 + c2) / 2
    hsum = h1 + h2
    hbar = np.where(np.abs(h1 - h2) <= 180, hsum / 2,
                   np.where(hsum < 360, (hsum + 360) / 2, (hsum - 360) / 2))
    hbar = np.where(c1 * c2 == 0, hsum, hbar)
    t = (1 - .17 * np.cos(np.radians(hbar - 30))
         + .24 * np.cos(np.radians(2 * hbar))
         + .32 * np.cos(np.radians(3 * hbar + 6))
         - .20 * np.cos(np.radians(4 * hbar - 63)))
    sl = 1 + .015 * (lbar - 50)**2 / np.sqrt(20 + (lbar - 50)**2)
    sc, sh = 1 + .045 * cbar, 1 + .015 * cbar * t
    rt = (-2 * np.sqrt(cbar**7 / (cbar**7 + 25**7))
          * np.sin(np.radians(60 * np.exp(-((hbar - 275) / 25)**2))))
    dl, dc, dh = (l2 - l1) / sl, (c2 - c1) / sc, delta_h / sh
    return np.sqrt(dl * dl + dc * dc + dh * dh + rt * dc * dh)


def main():
    # Independent published-pair check, not agreement with production C.
    assert abs(float(de00(np.array([50, 2.6772, -79.7751]),
                          np.array([50, 0, -82.7485]))) - 2.0425) < .00005
    y, x, c = np.indices((4, 5, 3))
    reference = ((17*x + 11*y + 7*c) % 29 - 2) / 32
    output = reference + ((3*x + 5*y + 2*c) % 9 - 4) / 64
    ppds = [12, 28.5, 60, 224]
    print('/* SPDX-License-Identifier: MIT */')
    print('/* Generated by sciede2000_reference.py; dense NumPy oracle. */')
    print('#ifndef LIBSIXEL_TEST_SCIEDE2000_REFERENCE_H')
    print('#define LIBSIXEL_TEST_SCIEDE2000_REFERENCE_H')
    emit('sciede2000_reference_xyz', reference)
    emit('sciede2000_output_xyz', output)
    emit('sciede2000_reference_ppd', ppds)
    means, maxima, bounds = [], [], []
    for ppd in ppds:
        a, b = filtered_lab(reference, ppd), filtered_lab(output, ppd)
        error = de00(a, b)
        means.append(error.mean())
        maxima.append(error.max())
        # Existing dense-filter budget: 5e-11 XYZ per component. The Lab
        # component bounds below use its worst derivative in the linear
        # branch, valid even for the fixture's signed filter lobes.
        lab_budget = 5e-11 * np.array([904, 7932, 3446])
        variations = [np.max(np.abs(de00(a + np.array(sign[:3]) * lab_budget,
                                         b + np.array(sign[3:]) * lab_budget)
                                   - error))
                      for sign in itertools.product([-1, 1], repeat=6)]
        bounds.append(max(variations))
    emit('sciede2000_reference_mean', means)
    emit('sciede2000_reference_max', maxima)
    emit('sciede2000_reference_corner_variation', bounds)
    print('#endif')


if __name__ == '__main__':
    main()
