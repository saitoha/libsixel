"""Emit frozen S-CIELAB fixtures with independent dense 2-D convolution.

Run with NumPy; this is not executed by TAP. No libsixel code is imported.
Coefficients and sampling convention: Zhang/Wandell's released MATLAB code,
https://github.com/wandell/SCIELAB-1996/tree/
cacbc977c07a29c3e92a1aec849ee63bba72e6bf
(cmatrix.m, separableFilters.m, gauss.m).

As documented for lsqa, normalize each resampled component to unit DC and
extend reflection repeatedly even when the image is smaller than support.
Use a dense 2-D mixture, not production's sequence of separable convolutions.
"""
import numpy as np


MATRIX = np.array([[.2787336, .7218031, -.1065520],
                   [-.4487736, .2898056, .0771569],
                   [.0859513, -.5899859, .5011089]])
PARAMS = [[(.05, 1.00327), (.225, .114416), (7, -.117686)],
          [(.0685, .616725), (.826, .383275)],
          [(.0920, .567885), (.6451, .432115)]]


def kernel(ppd, components):
    rate = max(1, int(np.ceil(224 / ppd)))
    grid = ppd * rate
    radius = int(np.ceil(grid / 2)) - 1
    x = np.arange(-radius, radius + 1)
    tent = 1 - np.abs(np.arange(1 - rate, rate)) / rate
    result = 0
    for spread, weight in components:
        g = np.exp(-4 * np.log(2) * (x / (spread * grid - 1)) ** 2)
        # Full convolution, then explicit crop/sample of original support.
        resampled = np.convolve(g, tent)
        middle = radius + rate - 1
        taps = np.arange(-(radius // rate), radius // rate + 1) * rate
        g = resampled[middle + taps]
        g /= g.sum()
        result = result + weight * np.outer(g, g)
    return result


def filtered_lab(xyz, ppd):
    opponent = xyz @ MATRIX.T
    filtered = np.empty_like(opponent)
    for channel, components in enumerate(PARAMS):
        k = kernel(ppd, components)
        pad = k.shape[0] // 2
        padded = np.pad(opponent[..., channel], pad, mode="symmetric")
        windows = np.lib.stride_tricks.sliding_window_view(padded, k.shape)
        filtered[..., channel] = np.einsum("ijkl,kl->ij", windows, k)
    xyz = filtered @ np.linalg.inv(MATRIX).T
    ratio = xyz / np.array([.9642, 1, .8249])
    f = np.where(ratio > (6 / 29) ** 3, np.cbrt(ratio),
                 ratio * (29 / 6) ** 2 / 3 + 4 / 29)
    return np.stack([116 * f[..., 1] - 16,
                     500 * (f[..., 0] - f[..., 1]),
                     200 * (f[..., 1] - f[..., 2])], axis=-1)


def emit(name, values):
    values = np.asarray(values).ravel()
    print(f"static double const {name}[{values.size}] = {{")
    for start in range(0, len(values), 3):
        print("    " + ", ".join(f"{v:.17g}" for v in values[start:start+3]) + ",")
    print("};")


def main():
    # Binary-fraction XYZ samples include extended and negative values.
    y, x, c = np.indices((4, 5, 3))
    reference = ((17*x + 11*y + 7*c) % 29 - 2) / 32
    output = reference + ((3*x + 5*y + 2*c) % 9 - 4) / 64
    ppds = [12, 28.5, 60, 224]
    print("/* SPDX-License-Identifier: MIT */")
    print("/* Generated by scielab_reference.py; dense NumPy 2-D oracle. */")
    print("#ifndef LIBSIXEL_TEST_SCIELAB_REFERENCE_H")
    print("#define LIBSIXEL_TEST_SCIELAB_REFERENCE_H")
    print("#if !defined(SIXEL_AMALGAMATION) || " + chr(92))
    print("    defined(BUILD_TEST_0028_SCIELAB_DENSE_REFERENCE)")
    emit("scielab_reference_xyz", reference)
    emit("scielab_output_xyz", output)
    emit("scielab_reference_ppd", ppds)
    means, maxima, maps = [], [], []
    for ppd in ppds:
        error = np.linalg.norm(filtered_lab(reference, ppd)
                               - filtered_lab(output, ppd), axis=-1)
        maps.extend(error.ravel())
        means.append(error.mean())
        maxima.append(error.max())
    emit("scielab_reference_mean", means)
    emit("scielab_reference_max", maxima)
    emit("scielab_reference_map", maps)
    print("#endif")
    print("#endif")


if __name__ == "__main__":
    main()
