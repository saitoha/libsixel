#!/usr/bin/env python3
"""Independent scalar oracle for CSS Color 4 local MINDE (2026-10-09).

Uses primary/white chromaticities and matrix inversion, never libsixel code.
Outputs canonical linear-sRGB triples; the C assertions allow 3e-5 for
independently rounded Oklab/adaptation matrices and the 1e-4 search endpoint.
"""
import math
from pathlib import Path


def mul(a, v):
    return [sum(x * y for x, y in zip(row, v)) for row in a]


def inverse(a):
    rows = [list(row) + [float(i == j) for j in range(3)]
            for i, row in enumerate(a)]
    for i in range(3):
        p = max(range(i, 3), key=lambda j: abs(rows[j][i]))
        rows[i], rows[p] = rows[p], rows[i]
        k = rows[i][i]
        rows[i] = [v / k for v in rows[i]]
        for j in range(3):
            if i != j:
                k = rows[j][i]
                rows[j] = [a - k * b for a, b in zip(rows[j], rows[i])]
    return [row[3:] for row in rows]


def rgb_matrix(white, primaries):
    columns = [[x / y, 1, (1 - x - y) / y] for x, y in primaries]
    raw = [list(row) for row in zip(*columns)]
    x, y = white
    scale = mul(inverse(raw), [x / y, 1, (1 - x - y) / y])
    return [[v * s for v, s in zip(row, scale)] for row in raw]


D65 = (.3127, .3290)
RGB = rgb_matrix(D65, [(.64, .33), (.30, .60), (.15, .06)])
BRADFORD = [[.8951, .2664, -.1614], [-.7502, 1.7135, .0367],
            [.0389, -.0685, 1.0296]]
LMS = [[.4122214708, .5363325363, .0514459929],
       [.2119034982, .6806995451, .1073969566],
       [.0883024619, .2817188376, .6299787005]]
LAB = [[.2104542553, .7936177850, -.0040720468],
       [1.9779984951, -2.4285922050, .4505937099],
       [.0259040371, .7827717662, -.8086757660]]


def lab(rgb):
    return mul(LAB, [math.copysign(abs(v) ** (1 / 3), v)
                     for v in mul(LMS, rgb)])


def linear(value):
    return mul(inverse(LMS), [v ** 3 for v in mul(inverse(LAB), value)])


def adapted(value, white, forward):
    if white == D65:
        return value
    def cone(w):
        x, y = w
        return mul(BRADFORD, [x / y, 1, (1 - x - y) / y])
    ratio = [a / b for a, b in zip(cone(white), cone(D65))]
    cone_value = mul(BRADFORD, value)
    return mul(inverse(BRADFORD), [v * r if forward else v / r
                                  for v, r in zip(cone_value, ratio)])


def mapping(origin, matrix, white):
    def device(value):
        return mul(inverse(matrix), adapted(mul(RGB, value), white, True))
    def canonical(value):
        return mul(inverse(RGB), adapted(mul(matrix, value), white, False))
    def inside(value):
        return all(0 <= v <= 1 for v in device(value))
    def clip(value):
        return canonical([min(1, max(0, v)) for v in device(value)])
    if inside(origin):
        return origin
    L, a, b = lab(origin)
    if L <= 0 or L >= 1:
        return canonical([float(L >= 1)] * 3)
    def clipped_at(chroma):
        value = linear([L, a * chroma / C, b * chroma / C])
        clipped = clip(value)
        delta = math.dist(lab(clipped), lab(value))
        return value, clipped, delta
    C = math.hypot(a, b)
    clipped = clip(origin)
    if math.dist(lab(clipped), lab(origin)) < .02:
        return clipped
    low, high = 0, C
    low_inside = True
    while high - low > .0001:
        mid = (low + high) / 2
        value, clipped, delta = clipped_at(mid)
        if low_inside and inside(value):
            low = mid
        elif delta < .02:
            if .02 - delta < .0001:
                return clipped
            low_inside, low = False, mid
        else:
            high = mid
    return clipped


spaces = [
    ('srgb', D65, [(.64, .33), (.30, .60), (.15, .06)]),
    ('display-p3', D65, [(.68, .32), (.265, .69), (.15, .06)]),
    ('adobe-rgb', D65, [(.64, .33), (.21, .71), (.15, .06)]),
    ('dci-p3', (.314, .351), [(.68, .32), (.265, .69), (.15, .06)])]
origins = [[1.4, -.1, .15], [-.2, 1.3, .4], [1.3, 1.15, -.1],
           [.03, -.02, .1], [1.1, -.02, .05]]
lines = ['/* Generated by gamut-reference.py, independently of libsixel. */',
         'static double const gamut_origins[][3] = {']
for v in origins:
    lines.append('    {\n        ' + ',\n        '.join(
        format(x, '.17g') for x in v) + '\n    },')
lines += ['};', 'static double const gamut_expected[][5][3] = {']
for name, white, primaries in spaces:
    lines.append('    { /* ' + name + ' */')
    for v in origins:
        result = mapping(v, rgb_matrix(white, primaries), white)
        lines.append('        {\n            ' + ',\n            '.join(
            format(x, '.17g') for x in result) + '\n        },')
    lines.append('    },')
lines.append('};')
Path(__file__).with_name('gamut-reference.h').write_text('\n'.join(lines) + '\n')
