#!/usr/bin/env python3
"""Independent CSS Color 4 Ray Trace oracle, pinned to 2026-10-09.

Derives matrices from chromaticities and tests all six faces instead of
using the production slab intersection. Never calls libsixel. The 3e-5
linear-channel budget covers independently rounded conversion matrices.
"""
import importlib.util
import math
from pathlib import Path

spec = importlib.util.spec_from_file_location(
    'gamut_reference', Path(__file__).with_name('gamut-reference.py'))
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)


def intersection(start, end, minimum=(0, 0, 0), maximum=(1, 1, 1)):
    direction = [b - a for a, b in zip(start, end)]
    hits = []
    for c, d in enumerate(direction):
        if abs(d) <= 1e-12:
            if not minimum[c] <= start[c] <= maximum[c]:
                return None
            continue
        for face in (minimum[c], maximum[c]):
            t = (face - start[c]) / d
            point = [a + t * v for a, v in zip(start, direction)]
            if t >= 0 and all(minimum[k] - 1e-10 <= p <= maximum[k] + 1e-10
                              for k, p in enumerate(point)):
                hits.append((t, point))
    return min(hits)[1] if hits else None


def mapping(origin, matrix, white, events=None):
    def device(value):
        return base.mul(base.inverse(matrix),
                        base.adapted(base.mul(base.RGB, value), white, True))
    def canonical(value):
        return base.mul(base.inverse(base.RGB),
                        base.adapted(base.mul(matrix, value), white, False))
    rgb = device(origin)
    if all(0 <= v <= 1 for v in rgb):
        return origin
    L, a, b = base.lab(origin)
    if L <= 0 or L >= 1:
        return canonical([float(L >= 1)] * 3)
    hue = math.atan2(b, a)
    anchor = device(base.linear([L, 0, 0]))
    last = rgb
    for i in range(4):
        if i:
            _, a, b = base.lab(canonical(rgb))
            C = math.hypot(a, b)
            rgb = device(base.linear([L, C * math.cos(hue), C * math.sin(hue)]))
        hit = intersection(anchor, rgb)
        if hit is None:
            if events is not None:
                events.append(('miss', i))
            rgb = last
            break
        if i and all(1e-12 < v < 1 - 1e-12 for v in rgb):
            if events is not None:
                events.append(('advance', i))
            anchor = rgb
        rgb = last = hit
    return canonical([min(1, max(0, v)) for v in rgb])


