#!/usr/bin/env python3
"""Independent Decimal RGB/Bradford oracle; no libsixel code is loaded."""
from decimal import Decimal as D, getcontext
from pathlib import Path
import struct
import colorsys
import zlib

getcontext().prec = 60

def matmul(a, b):
    return [[sum(x*y for x, y in zip(row, col)) for col in zip(*b)] for row in a]

def inverse(a):
    n = len(a)
    rows = [list(row) + [D(i == j) for j in range(n)] for i, row in enumerate(a)]
    for i in range(n):
        pivot = rows[i][i]
        rows[i] = [x/pivot for x in rows[i]]
        for j in range(n):
            if j != i:
                scale = rows[j][i]
                rows[j] = [x-scale*y for x, y in zip(rows[j], rows[i])]
    return [r[n:] for r in rows]

def vector(a, v):
    return [sum(x*y for x, y in zip(row, v)) for row in a]

def chroma(x, y):
    return [x/y, D(1), (1-x-y)/y]

bradford = [[D(x) for x in row.split()] for row in
            ['.8951 .2664 -.1614', '-.7502 1.7135 .0367', '.0389 -.0685 1.0296']]

def matrix(text):
    xy = list(map(D, text.split()))
    white = chroma(*xy[:2])
    columns = [chroma(*xy[i:i+2]) for i in (2, 4, 6)]
    raw = list(map(list, zip(*columns)))
    scales = vector(inverse(raw), white)
    raw = [[row[j]*scales[j] for j in range(3)] for row in raw]
    source_cone = vector(bradford, white)
    target_cone = vector(bradford, list(map(D, ['.9642', '1', '.8249'])))
    adaptation = matmul(inverse(bradford),
        [[bradford[i][j]*target_cone[i]/source_cone[i] for j in range(3)] for i in range(3)])
    return matmul(adaptation, raw)

srgb = matrix('.3127 .3290 .64 .33 .30 .60 .15 .06')
defs = [('.3127 .3290 .64 .33 .21 .71 .15 .06', D(563)/256),
        ('.3140 .3510 .68 .32 .265 .69 .15 .06', D('2.6'))]
samples = [[D.from_float(struct.unpack('f', struct.pack('f', float(x)))[0])
            for x in row] for row in [['.4', '.1', '.03'], ['-.18', '.8', '.012']]]
encoded = list(map(D, ['.23', '.47', '.81']))

lines = ['/* Generated by generate-named-output.py; independent 60-digit oracle. */',
         'static double const named_xyz[2][3] = {']
outputs = []
matrices = []
hls_outputs = []
min_margin = D(1)
for coords, exponent in defs:
    m = matrix(coords)
    matrices.append(m)
    hls_target = []
    xyz = vector(m, [x**exponent for x in encoded])
    lines.append('    {' + ', '.join(f'{v:.17g}' for v in xyz) + '},')
    target = []
    for sample in samples:
        linear = vector(inverse(m), vector(srgb, sample))
        rgb = [max(D(0), min(D(1), v**(1/exponent) if v >= 0 else -((-v)**(1/exponent)))) for v in linear]
        codes = [int(v*100+D('.5')) for v in rgb]
        for value, code in zip(rgb, codes):
            min_margin = min(min_margin, D('.5')-abs(value*100-code))
        target.append(codes)
        hue, light, sat = colorsys.rgb_to_hls(*map(float, rgb))
        fields = [int(((hue*360+120) % 360)+.5) % 360,
                  int(light*100+.5), int(sat*100+.5)]
        reconstructed = colorsys.hls_to_rgb(((fields[0]-120) % 360)/360,
                                            fields[1]/100, fields[2]/100)
        hls_target.append([int(v*100+.5) for v in reconstructed])
    outputs.append(target)
    hls_outputs.append(hls_target)
lines += ['};', 'static unsigned char const named_wire[2][2][3] = {']
for target in outputs:
    lines.append('    {' + ', '.join('{' + ', '.join(map(str, row)) + '}' for row in target) + '},')
lines += ['};', 'static double const named_matrix[2][3][3] = {']
for m in matrices:
    lines.append('    {' + ',\n     '.join('{' + ', '.join(f'{v:.17g}' for v in row) + '}' for row in m) + '},')
lines += ['};', 'static unsigned char const named_hls_wire[2][2][3] = {']
for target in hls_outputs:
    lines.append('    {' + ', '.join('{' + ', '.join(map(str, row)) + '}' for row in target) + '},')
lines += ['};', 'static unsigned char const named_primary_bytes[2][9] = {']
for (coords, exponent), m in zip(defs, matrices):
    codes = []
    for i in range(3):
        linear = vector(inverse(m), [row[i] for row in srgb])
        for value in linear:
            encoded_value = max(D(0), min(D(1), value**(1/exponent) if value >= 0 else D(0)))
            code = int(encoded_value*100+D('.5'))
            min_margin = min(min_margin, D('.5')-abs(encoded_value*100-code))
            codes.append((code*255+50)//100)
    lines.append('    {' + ', '.join(map(str, codes)) + '},')
# Two 16-bit P3 pixels travel through actual libpng/libtiff CMS loading.
# Read only the independent stored ICC coefficients, never a CMS result.
root = Path(__file__).parent
profile = (root / 'minimal-display-p3.icc').read_bytes()
tags = {}
for i in range(struct.unpack_from('>I', profile, 128)[0]):
    name, offset, size = struct.unpack_from('>4sII', profile, 132+12*i)
    tags[name] = profile[offset:offset+size]
p3matrix = list(map(list, zip(*[list(D(v)/65536 for v in
    struct.unpack_from('>3i', tags[name], 8)) for name in (b'rXYZ', b'gXYZ', b'bXYZ')])))
params = [D(v)/65536 for v in struct.unpack_from('>7i', tags[b'rTRC'], 12)]
g, a, b, c, d, e, f = params
raw = [15073, 30801, 53083, 0, 65535, 0]
loaded_margin = D(1)
lines += ['};', 'static unsigned char const named_loaded_wire[2][2][3] = {']
for (coords, exponent), m in zip(defs, matrices):
    target = []
    for i in (0, 3):
        source = [D(v)/65535 for v in raw[i:i+3]]
        linear = [(a*v+b)**g+e if v >= d else c*v+f for v in source]
        destination = vector(inverse(m), vector(p3matrix, linear))
        rgb = [max(D(0), min(D(1), v**(1/exponent) if v >= 0 else D(0))) for v in destination]
        target.append([int(v*100+D('.5')) for v in rgb])
        for v, code in zip(rgb, target[-1]):
            loaded_margin = min(loaded_margin, D('.5')-abs(v*100-code))
    lines.append('    {' + ', '.join('{' + ', '.join(map(str, row)) + '}' for row in target) + '},')
# Byte-exact source containers; ICC is shared with existing loader fixtures.
def chunk(name, data):
    return struct.pack('>I', len(data))+name+data+struct.pack('>I', zlib.crc32(name+data))
png = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', 2,1,16,2,0,0,0))
png += chunk(b'iCCP', b'P3\0\0'+zlib.compress(profile))
png += chunk(b'IDAT', zlib.compress(b'\0'+struct.pack('>6H', *raw)))+chunk(b'IEND',b'')
(root/'named-output-p3.png').write_bytes(png)
tags_tiff = [(256,4,1,2),(257,4,1,1),(258,3,3,None),(259,3,1,1),
             (262,3,1,2),(273,4,1,None),(277,3,1,3),(278,4,1,1),
             (279,4,1,12),(284,3,1,1),(34675,7,len(profile),None)]
base = 8+2+12*len(tags_tiff)+4
blob = struct.pack('<3H',16,16,16)+profile+struct.pack('<6H',*raw)
offsets = {258:base,34675:base+6,273:base+6+len(profile)}
tiff = b'II'+struct.pack('<HIH',42,8,len(tags_tiff))
for tag, typ, count, value in tags_tiff:
    tiff += struct.pack('<HHII',tag,typ,count,offsets[tag] if value is None else value)
(root/'named-output-p3.tif').write_bytes(tiff+struct.pack('<I',0)+blob)
lines += ['};', '']
Path(__file__).with_name('named-output.h').write_text('\n'.join(lines))
print('Minimum RGB101 half-bin margin:', min_margin)
print('Minimum loaded P3 RGB101 half-bin margin:', loaded_margin)
