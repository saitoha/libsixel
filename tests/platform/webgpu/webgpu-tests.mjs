async function diffusionEquivalence(createConverter) {
    const proto = GPUComputePassEncoder.prototype;
    const original = proto.dispatchWorkgroups;
    const map = GPUBuffer.prototype.mapAsync;
    const grids = [], reads = [];
    GPUBuffer.prototype.mapAsync = function (mode, ...args) {
        if (mode === GPUMapMode.READ) reads.push(this.size);
        return map.call(this, mode, ...args);
    };
    proto.dispatchWorkgroups = function (...args) {
        grids.push(args.slice(0, 2).join("x"));
        return original.apply(this, args);
    };
    try {
        for (const [lookup, method, expected] of cases) {
            const before = grids.length;
            reads.length = 0;
            const bytes = await convert(createConverter, 'force', method, lookup);
            const hex = await sha256(bytes);
            // Builders precede initialization. Point phases select one of
            // four 1024-position buckets; the collective keeps its 8x8 tile.
            const phases = grids.slice(-9, -1);
            const shape = lookup === 'blockcull' ? '3x2' : '16x1';
            // 221 indexes padded to a word plus the validation word.
            if (grids.length - before < 10 || !phases.every(g => g === shape) ||
                    reads.at(-1) !== 228 || hex !== expected)
                throw Error(lookup + '/' + method + ' dispatch or output differs');
        }
        return 'ok 1 - WebGPU diffusion matches Vulkan';
    } finally {
        GPUBuffer.prototype.mapAsync = map;
        proto.dispatchWorkgroups = original;
    }
}

// Both entry points report the same TAP result, including capability skips.
export async function runTest(name, createConverter) {
    try {
        if (!await globalThis.navigator?.gpu?.requestAdapter())
            return 'ok 1 # SKIP no WebGPU adapter';
        const tests = {paletteByteEquivalence, forceExitStatus, diffusionEquivalence};
        return await tests[name](createConverter);
    } catch (error) {
        return 'not ok 1 - ' + String(error).replace(/[\r\n]+/g, ' ');
    }
}
