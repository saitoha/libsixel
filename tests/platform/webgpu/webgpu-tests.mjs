// 17 x 13 exercises a partial input word and a partial output workgroup.
const header = new TextEncoder().encode('P6\n17 13\n255\n');
const image = new Uint8Array(header.length + 17 * 13 * 3);
image.set(header);
let seed = 31;
for (let i = header.length; i < image.length; ++i) {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
    image[i] = seed >>> 24;
}

function convert(createConverter, policy, method, lookup = 'none',
                 palette = 'xterm256', input = image, extra = [],
                 inputName = 'input.ppm', viaStdout = false) {
    return new Promise((resolve, reject) => {
        let fs;
        createConverter({
            arguments: ['--gpu-policy=' + policy, '--lookup-policy=' + lookup,
                '--precision-policy=8bit', '-d' + method,
                ...(palette ? ['-b' + palette] :
                    ['-Qheckbert', '-4adaptive-grid:solid=on', '-p16']),
                ...extra, ...(viaStdout ? [] : ['-o', 'output.six']),
                inputName],
            preRun: [module => {
                fs = module.FS;
                fs.writeFile(inputName, input);
            }],
            onRuntimeInitialized: () => {
                // Writing -o output.six fails with EBADF in some Emscripten
                // releases. Callers that must not depend on that path
                // capture stdout in MEMFS, after Emscripten opens its
                // standard streams.
                if (!viaStdout) return;
                fs.close(fs.getStream(1));
                fs.open('output.six', 'w');
            },
            onAbort: reason => reject(Error(String(reason))),
            onExit: status => {
                if (status) reject(Error(method + ' exited with ' + status));
                else resolve(fs.readFile('output.six'));
            }
        }).catch(reject);
    });
}

async function sha256(bytes) {
    const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', bytes));
    return Array.from(digest, b => b.toString(16).padStart(2, '0')).join('');
}

function solidSamplingImage() {
    // Above the scanner's admission threshold and not word-aligned.
    const width = 1027, height = 1025;
    const header = new TextEncoder().encode(`P6\n${width} ${height}\n255\n`);
    const input = new Uint8Array(header.length + width * height * 3);
    input.set(header);
    let at = header.length;
    for (let y = 0; y < height; ++y) {
        for (let x = 0; x < width; ++x) {
            const tile = (x >> 5) + 33 * (y >> 5);
            input[at++] = tile * 37;
            input[at++] = tile * 71;
            input[at++] = tile * 113;
        }
    }
    return input;
}

async function paletteByteEquivalence(createConverter) {
    const original = GPUQueue.prototype.submit;
    const dispatch = GPUComputePassEncoder.prototype.dispatchWorkgroups;
    let submissions = 0;
    const multiGroupPasses = [];
    GPUComputePassEncoder.prototype.dispatchWorkgroups = function (...groups) {
        if (groups.some(n => n > 1)) multiGroupPasses.push(groups[0]);
        return dispatch.apply(this, groups);
    };
    GPUQueue.prototype.submit = function (...args) {
        ++submissions;
        return original.apply(this, args);
    };
    try {
        for (const method of ['none', 'a_dither', 'x_dither', 'bluenoise']) {
            const before = submissions;
            const cpu = await convert(createConverter, 'off', method);
            if (submissions !== before) throw Error('GPU used with policy off');
            const gpu = await convert(createConverter, 'force', method);
            if (submissions === before || !cpu.length ||
                cpu.length !== gpu.length || !cpu.every((v, i) => v === gpu[i]))
                throw Error(method + ' submission or SIXEL bytes differ');
        }
        // Reference digests were generated by the native Vulkan backend with
        // the same PPM, fixed palette, byte precision and forced GPU policy.
        // CPU bucket memoization and Metal projection ties have different
        // contracts. Check the complete SIXEL stream against the byte ABI.
        const settings = ['none', 'a_dither', 'x_dither', 'bluenoise',
                          'bluenoise:strength=0.7:phase=7,31:channel=rgb'];
        const expected = {
            '5bit': [
                '28255c9b3300132ac0fa056f476f06762ddb46af9c361a37abfc5ee000f31e4a',
                '12d786b8395d06ce0dbfbe2678e2a06acc22b1f0a9d1426bf42c0ebe7f040715',
                '0115ec408d676d614427fca312a8da10c9ffb23645ad1a9d460104bef9ffccf8',
                'd32b074af3616d95be56f34655dac1e3ffccca0cdd2752d39672867b8ab09bb1',
                '174c94db471bd780592967cd544d13e7812f43bdd36e65a0e330702761bb4496',
            ],
            '6bit': [
                'faf9d9e961dec039cff0c03848e1e6de8a8071a6862268b76a2e928baca40aa2',
                'a3704ae718f1fcf7cbefa0c07aad2ef2047ced81bf5b044e1bf4448006774610',
                'f40d08139b8c8e99b7dc977d590bf3f5f079058abde0697f9d04707198fbe04a',
                'f56c6f9f7d18a9564384e9a787554a74f59f5abc4e9667da1501df786c03e13b',
                '08cf49fd1d04568842649ea5164a30f6643b9192db887efcc206472f01e861cf',
            ],
            'eytzinger': [
                '8bb48fd78720d4e8b915266e499466b5893c6b21758e2889e1bb9201a6bb90fa',
                'f51364900c74140361974b5e5024e825dbb1587899c5c0b597f5938b0322d06d',
                '8e63981c8d9b0901a917741ec733fdaf30c290788555250ba5330a7308403d30',
                '869f18a8405fa65cba0b94fe5d9931f0ec720f2993e5931b0dd82c5050ed5b73',
                'f02a14d90f3558821684db144d8b038211e1cabac1017a4dc2ccf80b2ad83288',
            ],
            'mahalanobis': [
                '3d354d3e1516685f0c71a0270daa4fd527a9dfad758350ddbdd51b8187f539db',
                '2167c5c74ab43dfde28cb2edb58c488f3e41cccc8c713b31733f4f06332afa46',
                'c22af9820e10bf7f731b61526c1e0316894bc2e5d3273ecaadfc5f27c3b983e3',
                '3d354d3e1516685f0c71a0270daa4fd527a9dfad758350ddbdd51b8187f539db',
                '30a072695f3a62906cbe4052352a992cfb7fa108576e1a656918d318c25c2899',
            ],
        };
        // These exact byte lookups choose the same register on distance ties.
        expected.ordered = expected.mahalanobis;
        expected.delaunay = expected.ordered;
        expected.rbc = expected.ordered;
        expected.vptree = expected.ordered;
        expected.certlut = expected.ordered;
        expected.gridlut = expected.ordered;
        for (const [lookup, digests] of Object.entries(expected)) {
            for (const [i, method] of settings.entries()) {
                const before = submissions, priorPasses = multiGroupPasses.length;
                const policy = i === 0 ? 'auto:palette_threshold=0' : 'force';
                const bytes = await convert(createConverter, policy, method, lookup);
                const hex = await sha256(bytes);
                // The 221-pixel point apply takes one workgroup. Only the
                // table builder spans multiple groups, once per fresh module.
                if ((lookup === '5bit' || lookup === '6bit') &&
                        multiGroupPasses.length - priorPasses !== 1)
                    throw Error(lookup + ' did not build its cell table exactly once');
                if (before === submissions || hex !== digests[i])
                    throw Error(lookup + '/' + method + ' differs from Vulkan');
            }
        }
        const short = await convert(createConverter, 'off', 'none', 'none', 'xterm16');
        // The 32^3 and 16^3 seed tables take 256 and 32 groups of 128 cells.
        // RBC assigns the 16 colors in a single group before packing rows.
        for (const [lookup, groups] of [['ordered', '16,256'],
                                        ['delaunay', '16,16,32'],
                                        ['rbc', '16,256'],
                                        ['vptree', '16,256'],
                                        ['certlut', '2,128'],
                                        ['gridlut', '128']]) {
            const before = multiGroupPasses.length;
            const gpu = await convert(createConverter, 'force', 'none', lookup, 'xterm16');
            if (multiGroupPasses.slice(before).join(',') !== groups ||
                    gpu.length !== short.length || !gpu.every((v, i) => v === short[i]))
                throw Error(lookup + ' short-palette builders or output differ');
        }
        // R64 builds the boundary table only when refinement is enabled.
        // The two Vulkan digests differ because refinement changes labels.
        for (const [options, groups, digest] of [
            ['', '128,128,128,2048',
             '29b5dc8c2ae64f5d77d9a8eddae0729f6e9c18bdced23ae39f23bd1f3e000840'],
            [':refine=0', '128,128,128',
             'a236d33d785a16971185d88200d3677adfb52ce85671a7c6cd2435d45e832cc8'],
        ]) {
            const before = multiGroupPasses.length;
            const gpu = await convert(createConverter, 'force', 'none',
                'fhedt' + options, 'xterm16');
            if (multiGroupPasses.slice(before).join(',') !== groups ||
                    await sha256(gpu) !== digest)
                throw Error('fhedt' + options + ' builders or output differ');
        }
        const sample = solidSamplingImage();
        const before = multiGroupPasses.length;
        const cpu = await convert(createConverter, 'off', 'none', 'none', '', sample);
        const gpu = await convert(createConverter, 'force', 'none', 'none', '', sample);
        // 1027 columns scanned at stride three take eleven groups of 32.
        if (!multiGroupPasses.slice(before).includes(11) ||
                await sha256(gpu) !== await sha256(cpu))
            throw Error('WebGPU solid-region sampling or SIXEL output differs');
        return 'ok 1 - WebGPU palette application preserves SIXEL bytes';
    } finally {
        GPUComputePassEncoder.prototype.dispatchWorkgroups = dispatch;
        GPUQueue.prototype.submit = original;
    }
}

// Asyncify must propagate errors raised after the adapter request resumes main.
async function forceExitStatus(createConverter) {
    const status = await new Promise((resolve, reject) => {
        createConverter({
            arguments: ['--gpu-policy=force', '--lookup-policy=fhedt:weights=3/1/1',
                '-dnone', '-bxterm256', '-o', 'output.six', 'input.ppm'],
            preRun: [module => module.FS.writeFile('input.ppm',
                'P6\n1 1\n255\nabc')],
            onExit: resolve,
            onAbort: reason => reject(Error(String(reason)))
        }).catch(reject);
    });
    if (status !== 1) throw Error('unexpected exit status ' + status);
    return 'ok 1 - force propagates the unsupported lookup exit status';
}

