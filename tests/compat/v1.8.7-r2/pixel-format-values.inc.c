#include <stdio.h>

#include <sixel.h>

#define SHOW(name) printf(#name "=%d\n", name)
#define SHOW_PAIR(name) \
    printf("SIXEL_" #name "=%d, " #name "=%d\n", SIXEL_##name, name)

int
main(void)
{
    /* Compare the public macros and every deprecated enum alias from r2.
     * The ABGR and BGRA formats had only macros in that release. */
    SHOW_PAIR(FORMATTYPE_COLOR);
    SHOW_PAIR(FORMATTYPE_GRAYSCALE);
    SHOW_PAIR(FORMATTYPE_PALETTE);
    SHOW_PAIR(PIXELFORMAT_RGB555);
    SHOW_PAIR(PIXELFORMAT_RGB565);
    SHOW_PAIR(PIXELFORMAT_RGB888);
    SHOW_PAIR(PIXELFORMAT_BGR555);
    SHOW_PAIR(PIXELFORMAT_BGR565);
    SHOW_PAIR(PIXELFORMAT_BGR888);
    SHOW_PAIR(PIXELFORMAT_ARGB8888);
    SHOW_PAIR(PIXELFORMAT_RGBA8888);
    SHOW(SIXEL_PIXELFORMAT_ABGR8888);
    SHOW(SIXEL_PIXELFORMAT_BGRA8888);
    SHOW_PAIR(PIXELFORMAT_G1);
    SHOW_PAIR(PIXELFORMAT_G2);
    SHOW_PAIR(PIXELFORMAT_G4);
    SHOW_PAIR(PIXELFORMAT_G8);
    SHOW_PAIR(PIXELFORMAT_AG88);
    SHOW_PAIR(PIXELFORMAT_GA88);
    SHOW_PAIR(PIXELFORMAT_PAL1);
    SHOW_PAIR(PIXELFORMAT_PAL2);
    SHOW_PAIR(PIXELFORMAT_PAL4);
    SHOW_PAIR(PIXELFORMAT_PAL8);
    return 0;
}
