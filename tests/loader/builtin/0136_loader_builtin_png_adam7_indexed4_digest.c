/* Verify Adam7 pass assembly for a four-bit indexed PNG. */

#include "loader_builtin_memory_test_common.h"

int
test_loader_0136_loader_builtin_png_adam7_indexed4_digest(int argc,
                                                          char **argv)
{
    static unsigned char const png[] = {
        0x89u, 0x50u, 0x4eu, 0x47u, 0x0du, 0x0au, 0x1au, 0x0au,
        0x00u, 0x00u, 0x00u, 0x0du, 0x49u, 0x48u, 0x44u, 0x52u,
        0x00u, 0x00u, 0x00u, 0x08u, 0x00u, 0x00u, 0x00u, 0x08u,
        0x04u, 0x03u, 0x00u, 0x00u, 0x01u, 0x41u, 0x26u, 0x93u,
        0x2eu, 0x00u, 0x00u, 0x00u, 0x0cu, 0x50u, 0x4cu, 0x54u,
        0x45u, 0xffu, 0x00u, 0x00u, 0x00u, 0xffu, 0x00u, 0x00u,
        0x00u, 0xffu, 0xffu, 0xffu, 0xffu, 0xfbu, 0x00u, 0x60u,
        0xf6u, 0x00u, 0x00u, 0x00u, 0x1eu, 0x49u, 0x44u, 0x41u,
        0x54u, 0x78u, 0xdau, 0x63u, 0x60u, 0x60u, 0x50u, 0x60u,
        0x60u, 0x62u, 0x30u, 0x04u, 0x42u, 0x66u, 0x45u, 0x10u,
        0x12u, 0x32u, 0x40u, 0x20u, 0x65u, 0x01u, 0x46u, 0x23u,
        0x34u, 0x02u, 0x00u, 0x49u, 0x78u, 0x03u, 0x6du, 0x6fu,
        0x65u, 0x2bu, 0x65u, 0x00u, 0x00u, 0x00u, 0x00u, 0x49u,
        0x45u, 0x4eu, 0x44u, 0xaeu, 0x42u, 0x60u, 0x82u
    };
    edge_frame_probe_t probe;
    SIXELSTATUS status;
    uint64_t digest;
    int result;

    (void)argc;
    (void)argv;
    status = SIXEL_FALSE;
    digest = 0u;
    result = edge_load_buffer("PNG Adam7 indexed4",
                              png,
                              sizeof(png),
                              1,
                              &probe,
                              &status);
    if (result != 0 || SIXEL_FAILED(status) || probe.callback_count != 1 ||
        probe.width[0] != 8 || probe.height[0] != 8 ||
        probe.pixelformat[0] != SIXEL_PIXELFORMAT_RGB888 ||
        probe.rgb_size[0] != 8u * 8u * 3u) {
        return 1;
    }
    digest = edge_digest_bytes(probe.rgb[0], probe.rgb_size[0]);
    return digest == UINT64_C(0xfef8d1c4e7efbfe5) ? 0 : 1;
}
