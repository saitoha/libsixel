#!/bin/sh
# SPDX-License-Identifier: MIT
# Embed one SPIR-V binary as C byte initializers. Bytes (not words) keep the
# file's own little-endian encoding independent of the build host; the
# runtime copies them into aligned words before vkCreateShaderModule.
set -eu
test "$#" -eq 2 || {
    echo "usage: $0 INPUT.spv OUTPUT.inc.h" >&2
    exit 2
}
source=$1
output=$2
directory=${output%/*}
test "$directory" != "$output" || directory=.
mkdir -p "$directory"
temporary=$output.tmp.$$
trap 'rm -f "$temporary"' EXIT HUP INT TERM
{
    echo '/* SPDX-License-Identifier: MIT */'
    echo '/* Generated by tools/embed-spirv.sh. Edit the .comp source. */'
    LC_ALL=C od -An -v -tx1 "$source" |
        LC_ALL=C sed -e 's/[0-9a-f][0-9a-f]/0x&,/g' -e 's/^ *//'
} > "$temporary"
mv -f "$temporary" "$output"
