IDENTIFIER = r"[A-Za-z_][A-Za-z0-9_]*"
NAME_AT_END = re.compile(IDENTIFIER + "$")
DECL_END = re.compile(r"\)[ \t]*(const[ \t]*)?;$")
TYPE_TOKENS = re.compile(IDENTIFIER)


def trim(text):
    return text.strip(" \t")


def symbol(name):
    return name if name.startswith("sixel_") else "sixel_" + name


def split_attributes(text):
    """Split attributes without splitting quoted strings or argument lists."""
    start = depth = 0
    quoted = False
    for index, char in enumerate(text):
        if char == '"' and (index == 0 or text[index - 1] != "\\"):
            quoted = not quoted
        if quoted:
            continue
        if char == "(":
            depth += 1
        elif char == ")" and depth:
            depth -= 1
        elif char == "," and not depth:
            yield trim(text[start:index])
            start = index + 1
    if trim(text[start:]):
        yield trim(text[start:])


def summary_arguments(line, name):
    """Read a contract summary's balanced parentheses as the AWK encoder does."""
    start = line.find(name + "(")
    if start == -1:
        return ""
    start += len(name) + 1
    depth = 1
    for index, char in enumerate(line[start:], start):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return line[start:index]
    return ""


def unquote(text):
    text = trim(text)
    return text[1:-1] if len(text) >= 2 and text[0] == text[-1] == '"' else text


class IdlCompiler:
    """Resolve IDL type names and emit C in declaration order."""

    def __init__(self, source):
        self.source = source.name
        self.lines = (line.rstrip("\n") for line in source)
        self.line_number = 0
        self.output = []
        self.types = {}
        self.interface_aliases = {}
        self.forwarded = set()
        self.attributes = []
        self.pending = {}

    def emit(self, *lines):
        self.output.extend(lines)

    def error(self, message):
        raise ValueError(f"{self.source}:{self.line_number}: {message}")

    def read(self, block):
        line = next(self.lines, None)
        if line is None:
            self.error(f"unterminated {block} block")
        self.line_number += 1
        return line

    def resolve(self, text):
        return TYPE_TOKENS.sub(lambda token: self.types.get(token[0], token[0]), text)

    def declarator(self, text):
        text = trim(text)
        name = NAME_AT_END.search(text)
        return self.resolve(text[:name.start()]) + name[0] if name else self.resolve(text)

    def take_attributes(self, line):
        # Keep the original spelling for contract comments and the parsed
        # values for declarations. Attributes can precede a declaration line.
        while line.startswith("["):
            match = re.match(r"\[([^\]]+)\][ \t]*", line)
            if not match:
                break
            self.attributes.append("[" + match[1] + "]")
            for item in split_attributes(match[1]):
                attr = re.fullmatch(r"(alias|classid|serviceid)\((.*)\)", item)
                if attr:
                    self.pending[attr[1]] = trim(attr[2])
                elif item in {"native", "const"}:
                    self.pending[item] = True
                elif item not in {"component", "opaque", "refcounted", "mutates", "default"} and not re.match(
                    r"(lifetime|invalidates|borrows|responsibility|forbid_state|serviceid)\(", item
                ):
                    self.error("unknown attribute: " + item)
            line = trim(line[match.end():])
        return line

    def emit_contract(self, lines, heading="IDL contract"):
        for line in lines:
            responsibility = summary_arguments(line, "responsibility")
            if responsibility:
                self.emit("/*", " * IDL responsibility:", " * - " + unquote(responsibility), " */", "")
        forbidden = []
        for line in lines:
            arguments = summary_arguments(line, "forbid_state")
            if arguments:
                forbidden.extend(unquote(item) for item in split_attributes(arguments))
        if forbidden:
            self.emit("/*", " * IDL forbidden state:", *(" * - " + item for item in forbidden), " */", "")
        self.emit("/*", " * " + heading + ":", *(" * " + line for line in lines), " */", "")

    def emit_comment(self, raw):
        self.emit(raw)
        while "*/" not in raw:
            raw = self.read("comment")
            self.emit(raw)

    def emit_struct_typedef(self, tag, alias):
        declaration = f"typedef struct {tag} {alias};"
        if len(declaration) <= 78:
            self.emit(declaration, "")
        else:
            self.emit(f"typedef struct {tag}", f"    {alias};", "")

    def read_declaration(self, line, contract=None):
        while not DECL_END.search(line):
            raw = self.read("decl")
            if contract is not None:
                contract.append(raw)
            line += " " + trim(raw)
        return trim(line[:-1])

    def parameters(self, text):
        parts = map(trim, text.split(","))
        return [
            self.declarator(re.sub(r"^(in|out|inout)[ \t]+", "", part))
            for part in parts
            if part not in ("", "void")
        ]

    def callable(self, declaration):
        before, opening, arguments = declaration.partition("(")
        arguments, closing, qualifier = arguments.rpartition(")")
        if not opening or not closing:
            self.error("invalid declaration: " + declaration)
        name = NAME_AT_END.search(trim(before))
        if not name:
            self.error("missing callable name: " + declaration)
        return self.resolve(trim(before[:name.start()])), name[0], self.parameters(arguments), trim(qualifier)

    def emit_function(self, line):
        result, name, args, _ = self.callable(self.read_declaration(line))
        self.emit(result)
        args = args or ["void"]
        self.emit(name + "(" + args[0] + ("," if len(args) > 1 else ");"))
        if len(args) > 1:
            self.emit(*("    " + arg + "," for arg in args[1:-1]), "    " + args[-1] + ");")
        self.emit("")

    def emit_callback(self, line):
        declaration = re.sub(r"^typedef[ \t]+", "", self.read_declaration(line), count=1)
        match = re.search(rf"\(\*({IDENTIFIER})\)", declaration)
        if not match:
            self.error("invalid callback typedef: " + declaration)
        result = self.resolve(trim(declaration[:match.start()]))
        _, opening, arguments = declaration[match.end():].partition("(")
        arguments, closing, _ = arguments.rpartition(")")
        if not opening or not closing:
            self.error("invalid callback arguments: " + declaration)
        prefix = "typedef " + result + ("" if result.endswith("*") else " ") + f"(*{match[1]})("
        args = self.parameters(arguments)
        if not args:
            self.emit(prefix + "void);", "")
        elif len(args) == 1 and len(prefix + args[0] + ");") <= 78:
            self.emit(prefix + args[0] + ");", "")
        else:
            self.emit(prefix, *("    " + arg + "," for arg in args[:-1]), "    " + args[-1] + ");", "")

    def emit_typedef(self, line):
        text = re.sub(r"[ \t]*;$", "", re.sub(r"^typedef[ \t]+", "", line))
        alias = NAME_AT_END.search(text)
        if not alias:
            self.error("invalid typedef: " + line)
        result = self.resolve(trim(text[:alias.start()]))
        if self.attributes:
            self.emit_contract(self.attributes + [line])
            self.attributes.clear()
        if self.pending.get("native"):
            self.types[alias[0]] = result
        else:
            name = alias[0] if alias[0].startswith("sixel_") else symbol(alias[0]) + "_t"
            self.types[alias[0]] = name
            self.emit(f"typedef {result} {name};", "")

    def emit_record(self, kind, name):
        tag = symbol(name)
        alias = tag + "_t"
        self.types[name] = alias
        self.emit(f"typedef {kind} {tag} {{")
        entries = []
        while True:
            line = trim(self.read("record" if kind == "struct" else "enum"))
            if line == "};":
                break
            if not line or line.startswith("//"):
                continue
            if kind == "enum":
                entries.append(line[:-1] if line.endswith(",") else line)
            else:
                comment = re.search(r"[ \t]+(/\*.*\*/)$", line)
                field = trim(line[:comment.start()]) if comment else line
                suffix = " " + line[comment.start() + 1:] if comment else ""
                if field.endswith(";"):
                    field = field[:-1]
                self.emit("    " + self.declarator(field) + ";" + suffix)
        self.emit(*("    " + entry + "," for entry in entries[:-1]))
        if entries:
            self.emit("    " + entries[-1])
        self.emit(f"}} {alias};", "")

    def register_interface(self, name):
        tag = symbol(name)
        if not (name.startswith("sixel_") and name.endswith("_interface")):
            tag += "_interface"
        alias = self.pending.get("alias") or self.interface_aliases.get(name, tag + "_t")
        vtbl = symbol(name) + "_vtbl_t"
        self.interface_aliases[name] = alias
        self.types[name] = alias
        self.types[name + "_vtbl"] = vtbl
        return tag, alias, vtbl

    def emit_method(self, result, name, args):
        pointer = result + ("" if result.endswith("*") else " ") + f"(*{name})"
        one_line = "    " + pointer + "(" + args[0] + ");"
        if len(args) == 1 and len(one_line) <= 78:
            self.emit(one_line)
            return
        if len(result) > 32:
            self.emit("    " + result, f"    (*{name})(")
        else:
            self.emit("    " + pointer + "(")
        self.emit(*("        " + arg + "," for arg in args[:-1]), "        " + args[-1] + ");")

    def emit_component(self, kind, name, line):
        if kind == "interface":
            tag, alias, vtbl = self.register_interface(name)
            line = f"interface {name} {{"
        else:
            identity = sum(bool(self.pending.get(key)) for key in ("classid", "serviceid"))
            if identity == 0:
                self.error("coclass is missing classid/serviceid: " + line)
            if identity == 2:
                self.error("coclass has classid and serviceid: " + line)
        contract = self.attributes + [line]
        self.attributes.clear()
        self.pending.clear()
        methods = []
        while True:
            raw = self.read(kind)
            line = trim(raw)
            if line == "};":
                contract.append(line)
                break
            if not line or line.startswith("//"):
                continue
            if line.startswith("/*"):
                self.emit_comment(raw)
                continue
            contract.append(raw)
            line = self.take_attributes(line)
            if not line:
                continue
            if kind == "interface":
                result, method, args, qualifier = self.callable(self.read_declaration(line, contract))
                const = self.pending.get("const") or qualifier == "const"
                receiver = alias + (" const *self" if const else " *self")
                methods.append((result, method, [receiver] + args))
            elif not re.fullmatch(rf"interface[ \t]+{IDENTIFIER}[ \t]*;", line):
                self.error("invalid coclass member: " + line)
            self.pending.clear()
            self.attributes.clear()
        if kind == "coclass":
            self.emit_contract(contract, "IDL coclass")
            self.pending.clear()
            self.attributes.clear()
            return
        if name not in self.forwarded:
            self.emit_struct_typedef(tag, alias)
        self.emit_contract(contract)
        self.emit(f"typedef struct {vtbl[:-2]} {{")
        for method in methods:
            self.emit_method(*method)
        self.emit(f"}} {vtbl};", "", f"struct {tag} {{", f"    {vtbl} const *vtbl;", "};", "")

    def compile(self):
        for raw in self.lines:
            self.line_number += 1
            line = trim(raw)
            if not line or line.startswith(("//", "#")):
                continue
            if line.startswith("/*"):
                self.emit_comment(raw)
                continue
            line = self.take_attributes(line)
            if not line:
                continue
            container = re.fullmatch(rf"(module|struct|enum|interface|coclass)[ \t]+({IDENTIFIER})[ \t]*\{{", line)
            forward = re.fullmatch(rf"(struct|interface)[ \t]+({IDENTIFIER})[ \t]*;", line)
            if line == "cpp_quote <<":
                while True:
                    raw = self.read("raw")
                    if raw == ">>":
                        break
                    self.emit(raw)
                self.emit("")
            elif container:
                kind, name = container.groups()
                if kind in ("struct", "enum"):
                    self.emit_record(kind, name)
                elif kind in ("interface", "coclass"):
                    self.emit_component(kind, name, line)
            elif forward:
                kind, name = forward.groups()
                if kind == "interface":
                    tag, alias, _ = self.register_interface(name)
                    self.emit_struct_typedef(tag, alias)
                    self.forwarded.add(name)
                    self.attributes.clear()
                else:
                    self.emit(f"struct {symbol(name)};")
            elif re.match(r"typedef[ \t]+", line):
                if "(*" in line:
                    self.emit_callback(line)
                    self.attributes.clear()
                else:
                    self.emit_typedef(line)
            elif "(" in line:
                self.emit_function(line)
                self.attributes.clear()
            elif line != "};":
                self.error("unexpected line: " + line)
            self.pending.clear()
        return HEADER + "".join(line + "\n" for line in self.output) + FOOTER


def main():
    if len(sys.argv) != 2:
        print(f"usage: {sys.argv[0]} INPUT.idl", file=sys.stderr)
        return 2
    try:
        with open(sys.argv[1], encoding="utf-8") as source:
            header = IdlCompiler(source).compile()
        sys.stdout.buffer.write(header.encode("utf-8"))
    except (OSError, ValueError) as exc:
        print(exc, file=sys.stderr)
        return 1
    return 0


