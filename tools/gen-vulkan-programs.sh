#!/bin/sh
# SPDX-License-Identifier: MIT
# Build the "vulkan.lookup-rgb8.v1" program matrix: every consumer kernel
# composed with every lookup policy, and every builder entry a policy
# declares, compiled to SPIR-V and embedded with the POSIX cksum CRC and
# length of its exact GLSL text. The runtime concatenates the same embedded
# chunks in the same order and finds a program by that key, so this script
# and sixel_vk_shader_module_compose() must compose texts identically:
#   consumer: PREFIX POLICY SUFFIX
#   builder:  BUILDER_PREFIX POLICY "\nvoid main()\n{\n    ENTRY();\n}\n"
# A policy lists its builder entries on one " * vulkan-builders:" line.
# A standalone component lists " * vulkan-stages:" and uses SOURCE + main.
#
# usage: gen-vulkan-programs.sh GLSLC OUTPUT BUILDER_PREFIX \
#            PREFIX:SUFFIX... -- POLICY.glsl...
set -eu
test "$#" -ge 5 || {
    echo "usage: $0 GLSLC OUTPUT BUILDER_PREFIX PREFIX:SUFFIX... --" \
        "POLICY.glsl..." >&2
    exit 2
}
glslc=$1
output=$2
builder_prefix=$3
shift 3
consumers=
while test "$#" -gt 0 && test "$1" != --; do
    consumers="$consumers $1"
    shift
done
test "$#" -gt 0 || {
    echo "$0: missing -- before the policy sources" >&2
    exit 2
}
shift
directory=${output%/*}
test "$directory" != "$output" || directory=.
mkdir -p "$directory"
work=$output.work.$$
temporary=$output.tmp.$$
trap 'rm -rf "$work" "$temporary"' EXIT HUP INT TERM
mkdir -p "$work"
count=0
table=

# Compile one composed text and append its embedded form.
emit() {
    "$glslc" -O --target-env=vulkan1.2 -fshader-stage=compute \
        "$work/text.comp" -o "$work/text.spv"
    # cksum emits exactly the CRC and byte count for standard input.
    # shellcheck disable=SC2046
    set -- $(LC_ALL=C cksum < "$work/text.comp")
    echo "static unsigned char const sixel_vk_composed_${count}[] = {"
    LC_ALL=C od -An -v -tx1 "$work/text.spv" |
        LC_ALL=C sed -e 's/[0-9a-f][0-9a-f]/0x&,/g' -e 's/^ */    /'
    echo "};"
    table="$table    { ${1}U, ${2}U, sixel_vk_composed_$count,
      sizeof(sixel_vk_composed_$count) },
"
    count=$((count + 1))
}

{
    echo '/* SPDX-License-Identifier: MIT */'
    echo '/* Generated by tools/gen-vulkan-programs.sh. Edit the .glsl'
    echo ' * sources. */'
    for policy in "$@"; do
        # Standalone components own their complete source and entry points.
        entries=$(LC_ALL=C sed -n \
            's/^ \* vulkan-stages: *//p' "$policy")
        if test -n "$entries"; then
            for entry in $entries; do
                {
                    cat "$policy"
                    printf '\nvoid main()\n{\n    %s();\n}\n' "$entry"
                } > "$work/text.comp"
                emit
            done
            continue
        fi
        for consumer in $consumers; do
            cat "${consumer%%:*}" "$policy" "${consumer#*:}" \
                > "$work/text.comp"
            emit
        done
        entries=$(LC_ALL=C sed -n \
            's/^ \* vulkan-builders: *//p' "$policy")
        for entry in $entries; do
            {
                cat "$builder_prefix" "$policy"
                printf '\nvoid main()\n{\n    %s();\n}\n' "$entry"
            } > "$work/text.comp"
            emit
        done
    done
    echo "static sixel_vk_composed_spirv_t const sixel_vk_composed_spirv[] = {"
    printf '%s' "$table"
    echo "};"
} > "$temporary"
mv -f "$temporary" "$output"
